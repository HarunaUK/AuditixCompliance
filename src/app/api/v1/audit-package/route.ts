import { createHash } from "node:crypto";
import { apiHandler, getApiContext } from "@/lib/api";
import { toCsv } from "@/lib/csv";
import { createZip } from "@/lib/zip";
import { db } from "@/lib/db";
import { registerCsv, stripLeadingHeading } from "@/lib/services/exports";
import { listSoa, soaCsv } from "@/lib/services/soa";
import { readinessReport } from "@/lib/services/readiness";
import { formatDateTime, titleCase } from "@/lib/utils";

export const dynamic = "force-dynamic";

/**
 * Auditor package: one ZIP an external auditor can open without a login —
 * SoA, control status, risk register, evidence index, the policy documents,
 * the Stage 2 readiness report and a manifest of SHA-256 checksums.
 */
export async function GET(request: Request) {
  return apiHandler(async () => {
    const context = await getApiContext(request);
    const workspaceId = context.workspaceId;

    const [soaRows, controlRows, risksCsv, evidenceCsv, policies, report] = await Promise.all([
      listSoa(workspaceId),
      db.workspaceControl.findMany({
        where: { workspaceId },
        include: {
          owner: { select: { name: true } },
          control: { select: { ref: true, title: true, framework: { select: { name: true } } } },
        },
        orderBy: { control: { ref: "asc" } },
      }),
      registerCsv(workspaceId, "risks"),
      registerCsv(workspaceId, "evidence"),
      db.policy.findMany({
        where: { workspaceId },
        include: { owner: { select: { name: true } }, controls: { select: { control: { select: { ref: true } } } } },
        orderBy: { title: "asc" },
      }),
      readinessReport(workspaceId),
    ]);

    const controlCsv = toCsv(
      ["Framework", "Ref", "Control", "Status", "Owner", "Due", "Justification", "Note"],
      controlRows.map((row) => [
        row.control.framework.name,
        row.control.ref,
        row.control.title,
        titleCase(row.status),
        row.owner?.name ?? "",
        row.dueDate ? row.dueDate.toISOString().slice(0, 10) : "",
        row.justification ?? "",
        row.note ?? "",
      ]),
    );

    const generatedAt = new Date();
    const fileSafe = (title: string) =>
      title
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-+|-+$/g, "")
        .slice(0, 60) || "policy";

    const readme = [
      `# Auditor package — ${context.membership.workspace.name}`,
      "",
      `Generated: ${formatDateTime(generatedAt)}`,
      `Generated by: ${context.user.name} (${context.user.email})`,
      `Stage 2 readiness: ${report.percent}% — ${report.label}`,
      "",
      "## Contents",
      "",
      "- `statement-of-applicability.csv` — applicability, justification and implementation per control",
      "- `control-status.csv` — implementation status with named owners and due dates",
      "- `risk-register.csv` — scoring, treatment, owner and due date per risk",
      "- `evidence-index.csv` — evidence artefacts with checksums and validity",
      "- `policies/` — every policy document as Markdown",
      "- `readiness-report.md` — the Stage 2 gate and its open blockers",
      "- `manifest.json` — SHA-256 checksum of every file in this package",
    ].join("\n");

    const readinessMd = [
      `# Stage 2 readiness — ${context.membership.workspace.name}`,
      "",
      `Overall: **${report.percent}%** (${report.label})`,
      "",
      `_${report.headline}_`,
      "",
      "## Phases",
      "",
      ...report.phases.map(
        (phase) => `- **${phase.title}** — ${phase.percent}% (${phase.metric}). ${phase.note ?? ""}`.trim(),
      ),
      "",
      "## Open blockers",
      "",
      ...(report.blockers.length
        ? report.blockers.map((blocker) => `- **${blocker.phase}** — ${blocker.title}`)
        : ["- None identified."]),
      "",
    ].join("\n");

    const files: { name: string; data: string }[] = [
      { name: "README.md", data: readme },
      { name: "statement-of-applicability.csv", data: `${soaCsv(soaRows)}\r\n` },
      { name: "control-status.csv", data: controlCsv },
      { name: "risk-register.csv", data: risksCsv },
      { name: "evidence-index.csv", data: evidenceCsv },
      { name: "readiness-report.md", data: readinessMd },
      ...policies.map((policy) => ({
        name: `policies/${fileSafe(policy.title)}.md`,
        data: [
          `# ${policy.title}`,
          "",
          `- Status: ${titleCase(policy.status)}`,
          `- Version: ${policy.version}`,
          `- Owner: ${policy.owner.name}`,
          policy.controls.length ? `- Controls: ${policy.controls.map((link) => link.control.ref).join(", ")}` : null,
          "",
          "---",
          "",
          stripLeadingHeading(policy.content),
          "",
        ]
          .filter((line): line is string => line !== null)
          .join("\n"),
      })),
    ];

    const manifest = {
      platform: "Auditix",
      workspace: context.membership.workspace.name,
      generatedAt: generatedAt.toISOString(),
      generatedBy: { name: context.user.name, email: context.user.email },
      readiness: { percent: report.percent, status: report.status, label: report.label },
      counts: {
        policies: policies.length,
        controls: controlRows.length,
        soaRows: soaRows.length,
        blockers: report.blockers.length,
      },
      checksums: Object.fromEntries(
        files.map((file) => [file.name, `sha256:${createHash("sha256").update(file.data, "utf8").digest("hex")}`]),
      ),
    };

    const archive = createZip([...files, { name: "manifest.json", data: JSON.stringify(manifest, null, 2) }], generatedAt);

    return new Response(archive as Uint8Array<ArrayBuffer>, {
      headers: {
        "content-type": "application/zip",
        "content-disposition": `attachment; filename="audit-package-${context.membership.workspace.slug}-${generatedAt
          .toISOString()
          .slice(0, 10)}.zip"`,
        "cache-control": "no-store",
      },
    });
  });
}
